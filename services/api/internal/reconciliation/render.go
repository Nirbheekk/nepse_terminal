// CoverageMarkdown renders the coverage report.
func CoverageMarkdown(rep *Report, cov []Coverage, fresh []jobs.DatasetStatus, sum jobs.Summary) string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("# Data coverage report\n\n")
	p("Generated: %s\n\n", rep.CheckedAt.Format(time.RFC3339))
	p("Legacy database: `%s`\n\n", rep.LegacyPath)
	p("This report is generated by `go run ./cmd/reconcile` from the live legacy NDJSON/SQLite\n")
	p("sources and the platform database. Nothing in it is hand-written.\n\n")

	p("## 1. What the platform holds\n\n")
	p("| Stream | Rows | Distinct %s | Sessions | First date | Last date | Archives | Last ingest |\n", "subject")
	p("|---|---:|---:|---:|---|---|---:|---|\n")
	for _, c := range cov {
		last := "never"
		if c.LastIngest != nil {
			last = c.LastIngest.UTC().Format("2006-01-02 15:04")
		}
		extra := c.Subject
		if extra == "" {
			extra = "—"
		}
		p("| `%s` | %d | %d | %d | %s | %s | %d | %s |\n",
			c.Stream, c.Rows, c.Distinct, c.Sessions,
			dash(c.FirstDate), dash(c.LastDate), c.Archives, last)
	}

	p("\n## 2. Dataset comparison against the legacy system\n\n")
	p("| Dataset | Legacy rows | Platform rows | Match | Note |\n")
	p("|---|---:|---:|---|---|\n")
	for _, d := range rep.Datasets {
		mark := "no"
		if d.Match {
			mark = "yes"
		} else if d.Expected {
			mark = "expected difference"
		}
		p("| `%s` | %d | %d | %s | %s |\n", d.Name, d.LegacyCount, d.PlatformCount, mark, d.Note)
	}

	if len(rep.Notes) > 0 {
		p("\n### Notes\n\n")
		for _, n := range rep.Notes {
			p("- %s\n", n)
		}
	}

	p("\n## 3. Freshness against SLA\n\n")
	p("| Stream | Rows | Latest observation | Age | SLA | Status | Severity |\n")
	p("|---|---:|---|---:|---:|---|---|\n")
	for _, f := range fresh {
		latest := "never"
		if f.LatestAt != nil {
			latest = f.LatestAt.UTC().Format("2006-01-02 15:04")
		}
		age := "—"
		if f.AgeSeconds != nil {
			age = humanAge(*f.AgeSeconds)
		}
		p("| `%s` | %d | %s | %s | %s | **%s** | %s |\n",
			f.Stream, f.Rows, latest, age, humanAge(int64(f.MaxAgeSeconds)), f.Status, f.Severity)
	}
	p("\nWorst status: **%s** (%d fresh, %d stale, %d unknown of %d datasets).\n\n",
		sum.Worst, sum.Fresh, sum.Stale, sum.Unknown, sum.Datasets)

	p("## 4. Gaps\n\n")
	gaps := 0
	for _, c := range cov {
		if c.Rows == 0 {
			p("- `%s` holds no rows.\n", c.Stream)
			gaps++
			continue
		}
		if c.Sessions == 1 && c.Stream != "companies" && c.Stream != "securities" {
			p("- `%s` covers a single session (%s); history before this date is not available from any source the platform is authorised to read.\n",
				c.Stream, dash(c.LastDate))
			gaps++
		}
	}
	for _, f := range fresh {
		if f.Status == "stale" {
			p("- `%s` is stale: last observation %s, SLA %s.\n", f.Stream,
				timeOrNever(f.LatestAt), humanAge(int64(f.MaxAgeSeconds)))
			gaps++
		}
	}
	if gaps == 0 {
		p("No gaps detected.\n")
	}

	p("\n## 5. How to reproduce\n\n")
	p("```bash\ncd platform\n")
	p("go run ./cmd/ingest -sqlite ../nepse.db -data ../data -force   # archive + load\n")
	p("go run ./cmd/reconcile -sqlite ../nepse.db -data ../data       # rewrite this report\n")
	p("```\n")
	return b.String()
}

// DiscrepancyMarkdown renders the comparison report.
func DiscrepancyMarkdown(rep *Report) string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	matches, mismatches, expected := rep.Totals()

	p("# Discrepancy report\n\n")
	p("Generated: %s\n\n", rep.CheckedAt.Format(time.RFC3339))
	p("**Verdict: %s** — %d checks matched, %d mismatched, %d expected difference(s).\n\n",
		strings.ToUpper(rep.Status()), matches, mismatches, expected)

	p("| | |\n|---|---:|\n")
	p("| Contracts compared field by field | %d |\n", rep.RowsCompared)
	p("| Contracts missing from the platform | %d |\n", rep.RowsMissing)
	p("| Field values that differ | %d |\n\n", rep.FieldMismatches)

	// Group checks by dataset for readability.
	byDataset := map[string][]Check{}
	var order []string
	for _, c := range rep.Checks {
		if _, ok := byDataset[c.Dataset]; !ok {
			order = append(order, c.Dataset)
		}
		byDataset[c.Dataset] = append(byDataset[c.Dataset], c)
	}
	sort.Strings(order)

	for _, ds := range order {
		checks := byDataset[ds]
		fail := 0
		for _, c := range checks {
			if !c.Match && !c.Expected {
				fail++
			}
		}
		p("## %s\n\n", ds)
		p("| Check | Legacy | Platform | Result |\n")
		p("|---|---|---|---|\n")
		for _, c := range checks {
			result := "match"
			switch {
			case c.Match:
			case c.Expected:
				result = "expected difference"
			default:
				result = "**MISMATCH**"
			}
			p("| %s | %s | %s | %s |\n", c.Field, code(c.Legacy), code(c.Platform), result)
		}
		if fail == 0 {
			p("\nAll checks in this dataset passed.\n\n")
		} else {
			p("\n%d check(s) failed.\n\n", fail)
		}
	}

	if len(rep.MismatchSamples) > 0 {
		p("## Contract-level differences (first %d)\n\n", len(rep.MismatchSamples))
		p("| Contract | Field | Legacy | Platform |\n|---|---|---|---|\n")
		for _, m := range rep.MismatchSamples {
			p("| `%s` | %s | %s | %s |\n", m.ContractID, m.Field, code(m.Legacy), code(m.Platform))
		}
		p("\n")
	}

	p("## Expected differences\n\n")
	anyExpected := false
	for _, c := range rep.Checks {
		if c.Match || !c.Expected {
			continue
		}
		anyExpected = true
		p("- **%s / %s** — legacy `%s`, platform `%s`. %s\n", c.Dataset, c.Field, c.Legacy, c.Platform, c.Note)
	}
	if !anyExpected {
		p("None.\n")
	}

	if len(rep.Notes) > 0 {
		p("\n## Notes\n\n")
		for _, n := range rep.Notes {
			p("- %s\n", n)
		}
	}

	p("\n## Method\n\n")
	p("Counts are compared directly. Aggregates are recomputed on both sides and compared\n")
	p("with a stated tolerance (0.01 for money, 1e-6 for rates). A sample of contracts is\n")
	p("then read from both stores and every field compared: symbol, trading date, quantity,\n")
	p("rate, amount, buyer, seller and execution time. Execution time is compared as an\n")
	p("instant, because the legacy store writes UTC without a zone marker while PostgreSQL\n")
	p("stores `timestamptz`.\n")
	return b.String()
}

func code(s string) string {
	if s == "" {
		return "`null`"
	}
	s = strings.ReplaceAll(s, "|", "\\|")
	if len(s) > 40 {
		s = s[:40] + "…"
	}
	return "`" + s + "`"
}

func dash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func timeOrNever(t *time.Time) string {
	if t == nil {
		return "never"
	}
	return t.UTC().Format("2006-01-02 15:04")
}

func humanAge(seconds int64) string {
	switch {
	case seconds < 60:
		return fmt.Sprintf("%ds", seconds)
	case seconds < 3600:
		return fmt.Sprintf("%dm", seconds/60)
	case seconds < 86400:
		return fmt.Sprintf("%dh", seconds/3600)
	default:
		return fmt.Sprintf("%dd", seconds/86400)
	}
}
